/**
 * common.h — 通用类型定义与宏
 *
 * 多联骨牌（polyomino）房间计数项目
 * 枚举 n×n 网格中所有 One-sided polyomino（允许旋转+平移，禁止翻转）
 * 并分类统计有洞/无洞的数量
 */

#ifndef COMMON_H
#define COMMON_H

#include <stdint.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* ================================================================
 * 编译期常量
 * ================================================================ */

/* 最大网格尺寸 */
#define MAX_N 6

/* 最大格子数 */
#define MAX_CELLS (MAX_N * MAX_N)  /* 36 */

/* 位图行步长（2的幂，方便位运算） */
#define STRIDE      8
#define STRIDE_SHIFT 3             /* log2(STRIDE) */

/* 归一化后坐标的安全边界（含旋转+padding余量） */
#define GRID_PAD (MAX_N + 4)       /* 10×10，足够容纳 -1 ~ MAX_N 坐标 */

/* ================================================================
 * 位图类型
 * ================================================================ */

/* 64位足够表示最多 8×8=64 个格子 */
typedef uint64_t mask_t;

/* ================================================================
 * 多联骨牌结构体（规范化表示）
 * ================================================================ */

typedef struct {
    mask_t cells;    /* 规范化位图：行优先，stride=STRIDE，左上角对齐(0,0) */
    int w;           /* 包围矩形宽度 */
    int h;           /* 包围矩形高度 */
    int size;        /* 格子数（即 popcount(cells)） */
} Poly;

/* ================================================================
 * 房间计数结果
 * ================================================================ */

typedef struct {
    int n;           /* 网格尺寸 1..MAX_N */
    int total;       /* 总房间数 */
    int no_hole;     /* 无洞房间数（亏格=0，单连通） */
    int has_hole;    /* 有洞房间数（亏格≥1） */
    int max_dim;     /* 该 n 下能容纳的最大 w/h（= n） */
} RoomCount;

#endif /* COMMON_H */
